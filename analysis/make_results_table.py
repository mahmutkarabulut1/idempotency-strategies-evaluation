#!/usr/bin/env python3
"""Emit a LaTeX table of measured results from results/aggregate.csv.

Writes paper/results_table.tex (\\input-able). Columns: E1 throughput (mean),
E1 p99 (mean ms), E2 duplicate side-effect violation rate. Skips gracefully if a
metric is missing. Run after the grid produces results/aggregate.csv.
"""
import os
import numpy as np
import pandas as pd

HERE = os.path.dirname(__file__)
AGG = os.path.join(HERE, "..", "results", "aggregate.csv")
OUT = os.path.join(HERE, "..", "paper", "results_table.tex")
ORDER = ["DB", "REDIS", "ZK", "KAFKA", "OUTBOX", "PAYLOAD_HASH"]


def mean_of(df, scenario, metric, strat, run=None):
    s = df[(df.scenario == scenario) & (df.metric == metric) & (df.strategy == strat)]
    if run is not None:
        s = s[s.run == run]
    return float(np.mean(s["value"])) if not s.empty else None


def fmt(v, nd=1):
    return "--" if v is None else f"{v:,.{nd}f}"


def main():
    if not os.path.exists(AGG):
        print(f"[make_results_table] {AGG} not found; run the grid first.")
        return
    df = pd.read_csv(AGG)
    strats = [s for s in ORDER if s in df.strategy.unique()]
    rows = []
    for s in strats:
        # E1 from the warm measurement run (run2); the cold first run is warm-up.
        thr = mean_of(df, "E1", "throughput", s, run="run2") or mean_of(df, "E1", "throughput", s)
        p99 = mean_of(df, "E1", "p99", s, run="run2") or mean_of(df, "E1", "p99", s)
        vr = mean_of(df, "E2", "violation_rate", s)
        label = s.replace("_", "\\_")  # escape for LaTeX text mode (e.g. PAYLOAD_HASH)
        rows.append(f"{label} & {fmt(thr)} & {fmt(p99)} & "
                    f"{'--' if vr is None else f'{vr:.4f}'} \\\\")
    table = (
        "% Auto-generated from results/aggregate.csv by analysis/make_results_table.py\n"
        "\\begin{table}[t]\\centering\n"
        "\\caption{Measured results: baseline throughput and p99 on the warm run "
        "(E1; cold warm-up run excluded), and duplicate side-effect violation rate "
        "under burst (E2).}\\label{tab:measured}\n"
        "\\small\\begin{tabular}{@{}lccc@{}}\n\\toprule\n"
        "Strategy & Thr.\\ (req/s) & p99 (ms) & DSEVR (E2) \\\\\n\\midrule\n"
        + "\n".join(rows) +
        "\n\\bottomrule\n\\end{tabular}\\end{table}\n"
    )
    with open(OUT, "w") as f:
        f.write(table)
    print(f"[make_results_table] wrote {OUT}\n")
    print(table)

    # ---- fault table (E4 partition + E5 timing) ----
    fault_out = os.path.join(HERE, "..", "paper", "fault_table.tex")
    e4 = [s for s in ORDER if not df[(df.scenario == "E4") & (df.strategy == s)].empty]
    e5 = [s for s in ["REDIS", "ZK", "REDIS_TS"]
          if not df[(df.scenario == "E5") & (df.strategy == s)].empty]
    if e4 or e5:
        lines = []
        for s in e4:
            er = mean_of(df, "E4", "error_rate", s)
            rec = mean_of(df, "E4", "recovery_s", s)
            vr = mean_of(df, "E4", "violation_rate", s)
            lines.append(f"E4 partition & {s} & {er*100:.1f}\\% & {rec:.2f}\\,s & "
                         f"{'0' if (vr or 0)==0 else f'{vr:.4f}'} \\\\")
        for s in e5:
            pe = mean_of(df, "E5", "premature_expirations", s)
            vr = mean_of(df, "E5", "violation_rate", s)
            label = s.replace("_", "\\_")  # escape for LaTeX text mode
            lines.append(f"E5 timing & {label} & {int(pe or 0)} prem.\\ & -- & "
                         f"{'0' if (vr or 0)==0 else f'{vr:.4f}'} \\\\")
        ftab = (
            "% Auto-generated by analysis/make_results_table.py\n"
            "\\begin{table}[t]\\centering\n"
            "\\caption{Measured fault behaviour: E4 reports request error rate and API "
            "recovery; E5 reports premature lease expirations. DSEVR (duplicate "
            "side-effect violation rate) is 0 throughout.}\\label{tab:fault}\n"
            "\\small\\begin{tabular}{@{}llccc@{}}\n\\toprule\n"
            "Scenario & Strategy & Error / Premature & Recovery & DSEVR \\\\\n\\midrule\n"
            + "\n".join(lines) +
            "\n\\bottomrule\n\\end{tabular}\\end{table}\n"
        )
        with open(fault_out, "w") as f:
            f.write(ftab)
        print(f"[make_results_table] wrote {fault_out}")


if __name__ == "__main__":
    main()
